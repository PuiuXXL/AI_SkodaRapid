"""Follow-up of the assistant's questions: confirmations, KSS answer, quiz (plan E3, D3, D8, K1, F3).

Many actions must wait for the driver's "yes" (plan section 6, column "Cere
confirmare"): the reminder ("Notat: ... Bine?"), the reply ("Îi scriu: ... Trimit?"),
the music ("Pun ceva mai energic?"), the stop ("Oprim la OMV?"). Other questions
expect a value: the KSS level 1-9, a quiz answer.

:class:`DialogManager` keeps the ONE question currently waiting for an answer and
turns the driver's inputs into results for core:

1. After ``handle_event`` returns, core calls :meth:`DialogManager.register` with
   the actions. Actions with ``needs_confirmation`` are put on hold; the others are
   returned for immediate execution (speak the question, etc.).
2. While something is pending, every input (voice text, nod, gesture - fused by
   ``assistant/answers.py``) goes to :meth:`DialogManager.handle`, which returns a
   :class:`DialogResult`:

   - ``execute``: actions now confirmed (``needs_confirmation=False``), to run;
     ``suggest_media`` becomes ``play_media``;
   - ``speak``: short replies to say (pre-generated clips such as "Notat.",
     "Trimis.", "Bine, am anulat." or quiz feedback);
   - ``events``: follow-up events for ``handle_event`` / P2:
     ``media_declined`` (music refused -> quiz offer), ``kss_answer`` (P2 uses the
     value to pick a break, plan D3), ``driver_refused`` (refusal during the
     fatigue dialog -> P2's rule C10);
   - ``handled=False`` when the input is not an answer (e.g. a new request): core
     then treats it as normal speech.

3. Unanswered questions expire after ``speech.pending_timeout_s`` (actions
   cancelled silently - never execute something the driver did not confirm).

The manager never executes anything itself and never touches safety.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from typing import Iterable, Literal, Optional

from assistant import cabin, media_search, music
from assistant.answers import InputEvent, fuse, parse_kss
from assistant.contract import Action, Event, State
from assistant.quiz import QuizSession
from assistant.refusal import is_refusal
from assistant.settings import cfg, get_texts
from assistant.textutil import fill, normalize

log = logging.getLogger("drivemate.assistant.dialog")

PendingKind = Literal["confirm", "kss", "quiz_offer", "quiz_answer", "choice"]

#: Clip said after a confirmed action (pre-generated by integrations/audio_clips.py).
CONFIRM_CLIPS: dict[str, str] = {
    "create_reminder": "confirm_noted",
    "reply_message": "confirm_sent",
    "suggest_stop": "confirm_ok",
    "set_preference": "confirm_ok",
    "complete_reminder": "confirm_done",
}

#: Words that stop a running quiz.
QUIZ_STOP_WORDS = ("gata", "stop", "ajunge", "destul", "nu mai vreau", "opreste")

#: How Romanian speech recognition may spell "quiz" (normalised).
QUIZ_WORDS = frozenset({"quiz", "quizul", "chiz", "kuiz", "kwiz", "chis"})


@dataclass
class Pending:
    """The question currently waiting for an answer.

    Attributes:
        kind: ``confirm`` (yes/no on held actions), ``kss`` (1-9), ``quiz_offer``
            (quiz / podcast / no), ``quiz_answer`` (answer to a quiz question),
            ``choice`` (which YouTube result, docs/assistant.md 6.1).
        actions: Actions held until "yes" (``confirm`` only).
        expires: Unix time after which the question is dropped.
        quiz: The running quiz (``quiz_answer`` only).
        options: All search results (``choice`` only); ``options[start:start+size]`` were offered.
        start: Index of the first offered option.
        size: How many options the question offered.
    """

    kind: PendingKind
    actions: list[Action] = field(default_factory=list)
    expires: float = 0.0
    quiz: Optional[QuizSession] = None
    options: list[dict] = field(default_factory=list)
    start: int = 0
    size: int = 0


@dataclass
class DialogResult:
    """What core must do after an input (see module docstring).

    Attributes:
        handled: True if the input answered the pending question.
        answer: ``yes`` / ``no`` / ``silence`` / ``refusal`` / ``kss`` / ``quiz`` / ``podcast`` / ``timeout``.
        channel: Input channel that gave the answer (``voice`` / ``nod`` / ``gesture``), for the log (plan E3).
        execute: Confirmed actions to execute now.
        cancelled: Actions dropped (answer "no", silence or timeout).
        speak: Short replies to say now (``source="RULE"``).
        events: Follow-up events (``media_declined``, ``kss_answer``, ``driver_refused``).
    """

    handled: bool = False
    answer: Optional[str] = None
    channel: Optional[str] = None
    execute: list[Action] = field(default_factory=list)
    cancelled: list[Action] = field(default_factory=list)
    speak: list[Action] = field(default_factory=list)
    events: list[Event] = field(default_factory=list)


def _text(key: str) -> str:
    """A text from the ``fallback`` group of texts.<language>.yaml."""
    return get_texts().get("fallback", {}).get(key, "")


def _clip(clip_id: str) -> Action:
    """A ``speak`` action that plays a pre-generated clip (text from the ``clips`` group)."""
    text = get_texts().get("clips", {}).get(clip_id, "")
    return Action(type="speak", to="driver", text=text, clip_id=clip_id, source="RULE")


def _say(text: str, question: bool = False) -> Action:
    """A short ``speak`` (or ``ask`` with free answer) generated by a rule."""
    if question:
        return Action(type="ask", to="driver", question=text, expects="free", source="RULE")
    return Action(type="speak", to="driver", text=text, source="RULE")


class DialogManager:
    """Holds the pending question and resolves the driver's answers (one per trip)."""

    def __init__(self) -> None:
        """Start with nothing pending."""
        self.pending: Optional[Pending] = None

    # ------------------------------------------------------------------ registering

    def register(self, actions: Iterable[Action], now: float) -> list[Action]:
        """Remember what the last answer of the assistant is waiting for.

        Args:
            actions: The actions returned by ``handle_event``.
            now: Current Unix time.

        Returns:
            The actions core can execute right away (everything except the ones held
            for confirmation). A new question replaces (and cancels) an older one.
        """
        actions = list(actions)
        held = [a for a in actions if a.needs_confirmation]
        immediate = [a for a in actions if not a.needs_confirmation]
        question = next((a for a in reversed(actions) if a.type == "ask"), None)
        expires = now + float(cfg("speech", "pending_timeout_s", default=20))

        if question is not None and question.reason == "quiz_offer":
            self.pending = Pending("quiz_offer", expires=expires)
        elif question is not None and question.expects == "choice" and question.options:
            size = sum(1 for o in question.options if o.get("offered")) or 1
            self.pending = Pending("choice", expires=expires, options=list(question.options), size=size)
        elif held:
            self.pending = Pending("confirm", actions=held, expires=expires)
        elif question is not None and question.expects == "kss":
            self.pending = Pending("kss", expires=expires)
        elif question is not None or any(a.type == "speak" for a in actions):
            # The assistant said something new with nothing to confirm (e.g. a cause or
            # a message interrupted a quiz): the older question is no longer the one the
            # driver is answering, so it is dropped.
            self.pending = None
        if held:
            log.info("holding %s until confirmation", [a.type for a in held])
        return immediate

    def has_pending(self, now: float) -> bool:
        """True if a question is waiting for an answer (expired ones are dropped)."""
        if self.pending is not None and now > self.pending.expires:
            log.info("pending %s expired", self.pending.kind)
            self.pending = None
        return self.pending is not None

    def expire(self, now: float) -> DialogResult:
        """Drop a timed-out question. Call periodically; returns what was cancelled."""
        if self.pending is None or now <= self.pending.expires:
            return DialogResult()
        cancelled = list(self.pending.actions)
        self.pending = None
        return DialogResult(handled=True, answer="timeout", cancelled=cancelled)

    def reset(self) -> None:
        """Forget the pending question (new trip, director reset, safety alert)."""
        self.pending = None

    # ------------------------------------------------------------------ answers

    def handle(
        self,
        inputs: Iterable[InputEvent],
        now: float,
        state: Optional[State] = None,
        fatigue_dialog: bool = False,
    ) -> DialogResult:
        """Resolve the pending question with the inputs seen since it was asked.

        Args:
            inputs: Voice text, nod and gesture inputs (any order).
            now: Current Unix time.
            state: Current state (cabin for volume / kid-safe quiz). Optional.
            fatigue_dialog: True inside the fatigue conversation (refusals count).

        Returns:
            A :class:`DialogResult`; ``handled=False`` when nothing pending or the
            inputs are not an answer.
        """
        inputs = list(inputs)
        if not self.has_pending(now):
            return DialogResult()
        kind = self.pending.kind
        if kind == "confirm":
            return self._confirm(inputs, state, fatigue_dialog)
        if kind == "kss":
            return self._kss(inputs)
        if kind == "quiz_offer":
            return self._quiz_offer(inputs, now, state)
        if kind == "choice":
            return self._choice(inputs, now, state)
        return self._quiz_answer(inputs, now)

    def _choice(self, inputs: list[InputEvent], now: float, state: Optional[State]) -> DialogResult:
        """Which YouTube result: "a doua" / "cel cu Metallica" / 👍 (one option) -> play it;
        "altceva" / 👎 -> the next results; ✋ / "lasă" -> cancel. Anything else is a new request."""
        pending = self.pending
        batch = pending.options[pending.start:pending.start + pending.size]
        pick: object = None
        channel = "voice"
        for item in sorted(inputs, key=lambda i: i.ts):
            if item.channel == "voice":
                pick = media_search.parse_choice(item.value, batch)
            elif item.channel == "gesture" and item.value == "Open_Palm":
                pick, channel = "cancel", "gesture"
            elif (item.channel == "gesture" and item.value == "Thumb_Down") or (item.channel == "nod" and item.value == "no"):
                pick, channel = "next", item.channel
            elif len(batch) == 1 and ((item.channel == "gesture" and item.value == "Thumb_Up")
                                      or (item.channel == "nod" and item.value == "yes")):
                pick, channel = 0, item.channel
            if pick is not None:
                break
        if pick is None:
            return DialogResult()

        if pick == "cancel":
            self.pending = None
            return DialogResult(handled=True, answer="silence", channel=channel)
        if pick == "next":
            nxt = pending.start + pending.size
            if nxt >= len(pending.options):
                self.pending = None
                return DialogResult(handled=True, answer="no", channel=channel, speak=[_say(_text("youtube_no_more"))])
            size = min(pending.size, len(pending.options) - nxt)
            question, _ = media_search.choice_question(pending.options, nxt, size)
            pending.start, pending.size, pending.expires = nxt, size, self._expiry(now)
            media_search.prefetch(o["track_id"][3:] for o in pending.options[nxt:nxt + size])
            ask = Action(type="ask", to="driver", question=question, expects="choice", options=pending.options,
                         reason="media_choice", source="RULE")
            return DialogResult(handled=True, answer="no", channel=channel, speak=[ask])

        option = batch[int(pick)]
        self.pending = None
        volume = music.volume_for(state) if state is not None else None
        play = Action(type="play_media", track_id=option["track_id"], title=option.get("title"), volume=volume,
                      reason="driver_request", source="RULE")
        return DialogResult(handled=True, answer="choice", channel=channel, execute=[play],
                            speak=[_say(media_search.playing_text(option))])

    def _confirm(self, inputs: list[InputEvent], state: Optional[State], fatigue_dialog: bool) -> DialogResult:
        """Yes -> execute the held actions; no / silence / refusal -> cancel them.

        A yes with a concrete wish to a music offer ("da, ceva metal energic") is not a plain
        yes: the offer is dropped and the wish goes back as ``driver_speech`` (YouTube search).
        """
        held = self.pending.actions
        if any(a.type == "suggest_media" for a in held):
            wish = next((i.value for i in inputs if i.channel == "voice" and media_search.is_specific_wish(i.value)),
                        None)
            if wish is not None and cfg("youtube", "enabled", default=True):
                self.pending = None
                return DialogResult(handled=True, answer="yes", channel="voice", cancelled=list(held),
                                    events=[Event(type="driver_speech", data={"text": wish})])
        answer = fuse(inputs, fatigue_dialog=fatigue_dialog)
        if answer is None:
            return DialogResult()
        self.pending = None
        result = DialogResult(handled=True, answer=answer.value, channel=answer.channel)

        if answer.value == "yes":
            for action in held:
                result.execute.append(self._confirmed(action, state))
            clip = next((CONFIRM_CLIPS[a.type] for a in held if a.type in CONFIRM_CLIPS), None)
            if clip:
                result.speak.append(_clip(clip))
            return result

        result.cancelled = list(held)
        if any(a.type == "suggest_media" for a in held) and answer.value == "no":
            result.events.append(Event(type="media_declined", data={}))  # plan D8: -> quiz offer
        elif answer.value == "no":
            result.speak.append(_clip("confirm_cancelled"))
        elif answer.value == "refusal":
            result.events.append(Event(type="driver_refused", data={}))
        return result  # "silence" (open palm): cancel quietly

    @staticmethod
    def _confirmed(action: Action, state: Optional[State]) -> Action:
        """The executable form of a confirmed action (``suggest_media`` -> ``play_media``)."""
        if action.type == "suggest_media":
            volume = music.volume_for(state) if state is not None else None
            return Action(type="play_media", track_id=action.track_id, volume=volume,
                          reason=action.reason, source=action.source)
        return action.model_copy(update={"needs_confirmation": False})

    def _kss(self, inputs: list[InputEvent]) -> DialogResult:
        """KSS value -> ``kss_answer`` event; refusal -> ``driver_refused`` (fatigue dialog)."""
        for item in sorted(inputs, key=lambda i: i.ts):
            if item.channel == "voice":
                if is_refusal(item.value):
                    self.pending = None
                    return DialogResult(handled=True, answer="refusal", channel="voice",
                                        events=[Event(type="driver_refused", data={"text": item.value})])
                value = parse_kss(item.value)
                if value is not None:
                    self.pending = None
                    return DialogResult(handled=True, answer="kss", channel="voice",
                                        events=[Event(type="kss_answer", data={"value": value})])
            elif item.channel == "gesture" and item.value in ("Open_Palm", "Thumb_Down"):
                self.pending = None  # ✋ / 👎 in the fatigue dialog = refusal (plan D10, E3)
                return DialogResult(handled=True, answer="refusal", channel="gesture",
                                    events=[Event(type="driver_refused", data={})])
        return DialogResult()

    def _quiz_offer(self, inputs: list[InputEvent], now: float, state: Optional[State]) -> DialogResult:
        """"quiz" / yes -> first question; "podcast" -> play it; no -> acknowledge."""
        voice = " ".join(normalize(i.value) for i in inputs if i.channel == "voice")
        found = music.podcasts(state) if state is not None else []
        if "podcast" in voice.split() and found:
            self.pending = None
            track = found[0]
            volume = music.volume_for(state) if state is not None else None
            return DialogResult(handled=True, answer="podcast", channel="voice",
                                execute=[Action(type="play_media", track_id=track.id, volume=volume,
                                                reason="disengagement", source="RULE")])
        answer = fuse(inputs)
        wants_quiz = bool(QUIZ_WORDS & set(voice.split())) or (answer is not None and answer.value == "yes")
        if wants_quiz:
            return self._start_quiz(now, state, channel=answer.channel if answer else "voice")
        if answer is not None:  # no / silence
            self.pending = None
            result = DialogResult(handled=True, answer=answer.value, channel=answer.channel)
            if answer.value == "no":
                result.speak.append(_clip("confirm_ok"))
            return result
        return DialogResult()

    def _start_quiz(self, now: float, state: Optional[State], channel: str) -> DialogResult:
        """Create a quiz session and ask its first question."""
        quiz = QuizSession(kid_safe_only=cabin.has_child(state) if state is not None else False)
        if quiz.current is None:
            self.pending = None
            return DialogResult(handled=True, answer="quiz", channel=channel, speak=[_say(_text("quiz_unavailable"))])
        self.pending = Pending("quiz_answer", quiz=quiz, expires=self._expiry(now))
        return DialogResult(handled=True, answer="quiz", channel=channel, speak=[_say(quiz.current.q, question=True)])

    def _quiz_answer(self, inputs: list[InputEvent], now: float) -> DialogResult:
        """Score a quiz answer, then ask the next question or announce the score."""
        quiz = self.pending.quiz
        voice = next((i for i in sorted(inputs, key=lambda i: i.ts) if i.channel == "voice"), None)
        gesture_stop = any(i.channel == "gesture" and i.value in ("Open_Palm", "Thumb_Down") for i in inputs)
        if gesture_stop or (voice is not None and (is_refusal(voice.value)
                                                   or any(w in normalize(voice.value) for w in QUIZ_STOP_WORDS))):
            self.pending = None
            return DialogResult(handled=True, answer="no", channel="gesture" if gesture_stop else "voice",
                                speak=[_say(_text("quiz_stopped"))])
        if voice is None:
            return DialogResult()
        correct, question = quiz.answer(voice.value)
        feedback = _text("quiz_correct") if correct else fill(_text("quiz_wrong"), answer=question.say)
        result = DialogResult(handled=True, answer="quiz", channel="voice")
        if quiz.current is not None:
            result.speak.append(_say(feedback))
            result.speak.append(_say(quiz.current.q, question=True))
            self.pending.expires = self._expiry(now)
        else:
            self.pending = None
            result.speak.append(_say(feedback))
            result.speak.append(_say(fill(_text("quiz_end"), score=quiz.score, total=quiz.total)))
        return result

    @staticmethod
    def _expiry(now: float) -> float:
        """Expiry time for a new pending question."""
        return now + float(cfg("speech", "pending_timeout_s", default=20))
