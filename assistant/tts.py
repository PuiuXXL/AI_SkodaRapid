"""Text-to-speech for the assistant's voice (plan E1, D4), with edge-tts.

How speech reaches the speakers:

1. Core gets a ``speak`` / ``ask`` action from :func:`assistant.client.handle_event`.
2. Core calls :func:`speak_message` to turn it into the ``speak`` message for the
   browser (``/ws/ui``). The text is split into sentences and each sentence gets
   an id and a URL ``/tts/<id>.mp3``. Synthesis of every sentence starts
   immediately in the background (prefetch).
3. The browser voice player (``dashboard/src/voice/player.js``) plays the sentences
   one by one, fetching ``/tts/<id>.mp3`` from :mod:`assistant.router`.

Playing sentence by sentence is what lets the assistant stop mid-phrase when the
driver looks in the mirror and resume with "...cum ziceam" (plan D4).

Critical audio (alarms, "Ești bine?", passenger instructions...) never uses this
path: it is pre-generated by ``integrations/audio_clips.py`` (plan C3, E7).
"""

from __future__ import annotations

import asyncio
import hashlib
import logging
from collections import OrderedDict
from typing import Any, Optional

import edge_tts

from assistant.contract import Action
from assistant.settings import cfg
from assistant.textutil import split_sentences

log = logging.getLogger("drivemate.assistant.tts")

#: URL prefix of pre-generated clips (dashboard/public/sounds/clips, served by the UI).
CLIP_URL_PREFIX = "/sounds/clips"


def default_voice() -> str:
    """Neural voice for the configured language (``tts.voices`` in assistant.yaml)."""
    language = cfg("language", default="ro")
    return cfg("tts", "voices", language, default="ro-RO-AlinaNeural")


async def synthesize(text: str, voice: Optional[str] = None, rate: Optional[str] = None) -> bytes:
    """Synthesize ``text`` to mp3 bytes with edge-tts (needs internet).

    Args:
        text: The sentence to say.
        voice: edge-tts voice name; defaults to :func:`default_voice`.
        rate: Speed such as ``"+5%"``; defaults to ``tts.rate``.

    Returns:
        The mp3 audio.

    Raises:
        RuntimeError: When edge-tts returns no audio.
    """
    communicate = edge_tts.Communicate(text, voice or default_voice(), rate=rate or cfg("tts", "rate", default="+0%"))
    audio = bytearray()
    async for chunk in communicate.stream():
        if chunk.get("type") == "audio":
            audio.extend(chunk["data"])
    if not audio:
        raise RuntimeError(f"edge-tts returned no audio for {text!r}")
    return bytes(audio)


class SpeechCache:
    """Registry of sentences to say, with an in-memory LRU cache of their audio.

    A sentence is identified by a short hash of (voice, rate, text), so the same
    sentence is synthesized only once ("Ok." is cached forever in practice).
    """

    def __init__(self, size: Optional[int] = None) -> None:
        """Create an empty cache holding at most ``size`` audio files (``tts.cache_size``)."""
        self._size = size or int(cfg("tts", "cache_size", default=256))
        self._texts: dict[str, tuple[str, str, str]] = {}
        self._audio: OrderedDict[str, bytes] = OrderedDict()
        self._pending: dict[str, asyncio.Task] = {}

    @staticmethod
    def make_id(text: str, voice: str, rate: str) -> str:
        """Stable id of a sentence (16 hex chars)."""
        return hashlib.sha1(f"{voice}|{rate}|{text}".encode("utf-8")).hexdigest()[:16]

    def register(self, text: str, voice: Optional[str] = None, rate: Optional[str] = None) -> str:
        """Remember a sentence so it can later be fetched by id.

        Args:
            text: The sentence.
            voice: Voice name (default voice when None).
            rate: Speech rate (``tts.rate`` when None).

        Returns:
            The sentence id used in ``/tts/<id>.mp3``.
        """
        voice = voice or default_voice()
        rate = rate or cfg("tts", "rate", default="+0%")
        speech_id = self.make_id(text, voice, rate)
        self._texts[speech_id] = (text, voice, rate)
        return speech_id

    def known(self, speech_id: str) -> bool:
        """True if the id was registered."""
        return speech_id in self._texts

    def prefetch(self, speech_id: str) -> None:
        """Start synthesizing in the background (needs a running event loop)."""
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            return  # no loop (e.g. called from sync code): audio is made on first request
        if speech_id in self._audio or speech_id in self._pending or speech_id not in self._texts:
            return
        self._pending[speech_id] = loop.create_task(self._synthesize(speech_id))

    async def get(self, speech_id: str) -> bytes:
        """Return the mp3 for a registered sentence, synthesizing it if needed.

        Raises:
            KeyError: Unknown id.
            RuntimeError: Synthesis failed (no internet, invalid voice...).
        """
        if speech_id in self._audio:
            self._audio.move_to_end(speech_id)
            return self._audio[speech_id]
        if speech_id not in self._texts:
            raise KeyError(speech_id)
        task = self._pending.get(speech_id)
        if task is None or task.get_loop() is not asyncio.get_running_loop():
            # No prefetch running, or it was started on another event loop (can happen
            # when core and the router run in different loops / test clients).
            task = asyncio.ensure_future(self._synthesize(speech_id))
            self._pending[speech_id] = task
        return await asyncio.shield(task)

    async def _synthesize(self, speech_id: str) -> bytes:
        """Synthesize one registered sentence and store it in the LRU cache."""
        text, voice, rate = self._texts[speech_id]
        try:
            audio = await synthesize(text, voice, rate)
        finally:
            self._pending.pop(speech_id, None)
        self._audio[speech_id] = audio
        while len(self._audio) > self._size:
            self._audio.popitem(last=False)
        return audio


#: Process-wide cache shared by core (registration) and the router (serving).
speech_cache = SpeechCache()

_counter = 0


def speak_message(action: Action, utterance_id: Optional[str] = None) -> dict[str, Any]:
    """Build the ``speak`` message sent to the browser on ``/ws/ui`` for a speak/ask action.

    Message format (P3 proposal, documented in docs/assistant.md)::

        {
          "type": "speak",
          "id": "u12",                 # utterance id, echoed back in speak_done
          "to": "driver",
          "is_question": true,         # true for ask -> core opens the dialog window
          "expects": "yes_no",         # for ask only
          "text": "Pare monoton. Pun ceva mai energic?",
          "clip_url": null,            # pre-generated clip that replaces TTS, if any
          "sentences": [ {"id": "3f2a...", "text": "...", "url": "/tts/3f2a....mp3"} ]
        }

    Args:
        action: A ``speak`` or ``ask`` action.
        utterance_id: Optional id; generated (``u1``, ``u2``...) when None.

    Returns:
        The message as a dict (serialise with orjson / json).

    Raises:
        ValueError: If the action is not ``speak`` / ``ask``.
    """
    global _counter
    if action.type not in ("speak", "ask"):
        raise ValueError(f"speak_message needs a speak/ask action, got {action.type}")
    text = (action.text if action.type == "speak" else action.question) or ""
    if utterance_id is None:
        _counter += 1
        utterance_id = f"u{_counter}"
    sentences = []
    if not action.clip_id:
        for sentence in split_sentences(text):
            speech_id = speech_cache.register(sentence)
            speech_cache.prefetch(speech_id)
            sentences.append({"id": speech_id, "text": sentence, "url": f"/tts/{speech_id}.mp3"})
    return {
        "type": "speak",
        "id": utterance_id,
        "to": action.to or "driver",
        "is_question": action.type == "ask",
        "expects": action.expects,
        "text": text,
        "clip_url": f"{CLIP_URL_PREFIX}/{action.clip_id}.mp3" if action.clip_id else None,
        "sentences": sentences,
    }
